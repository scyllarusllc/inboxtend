// Copies the third-party front-end files the app serves into static/vendor (committed, so that running the app needs
// no Node), and writes countries.py's code list from the flags that exist. Re-run after changing a version in
// package.json:   npm run vendor
import {cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
const version = name => JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8')).version;

// --- Font Awesome Free (icons)
{
  const from = 'node_modules/@fortawesome/fontawesome-free', to = 'static/vendor/fontawesome';
  rmSync(to, {recursive: true, force: true});
  mkdirSync(`${to}/css`, {recursive: true}); mkdirSync(`${to}/webfonts`, {recursive: true});
  for (const f of ['fontawesome.min.css', 'solid.min.css', 'regular.min.css']) cpSync(`${from}/css/${f}`, `${to}/css/${f}`);
  for (const f of ['fa-solid-900.woff2', 'fa-regular-400.woff2']) cpSync(`${from}/webfonts/${f}`, `${to}/webfonts/${f}`);
  cpSync(`${from}/LICENSE.txt`, `${to}/LICENSE.txt`);
  console.log(`Font Awesome Free ${version('@fortawesome/fontawesome-free')} -> ${to}`);
}

// --- flag-icons (country flags): the 4x3 SVGs of two-letter codes only
{
  const from = 'node_modules/flag-icons', to = 'static/vendor/flag-icons';
  rmSync(to, {recursive: true, force: true});
  mkdirSync(`${to}/css`, {recursive: true}); mkdirSync(`${to}/flags/4x3`, {recursive: true});
  cpSync(`${from}/css/flag-icons.min.css`, `${to}/css/flag-icons.min.css`);
  const codes = readdirSync(`${from}/flags/4x3`).filter(f => /^[a-z]{2}\.svg$/.test(f)).map(f => f.slice(0, 2));
  for (const c of codes) cpSync(`${from}/flags/4x3/${c}.svg`, `${to}/flags/4x3/${c}.svg`);
  cpSync(`${from}/LICENSE`, `${to}/LICENSE`);
  // Not countries: xx (unknown flag), eu, un. The AI may only answer with a code that has a flag and is a country.
  const countries = codes.filter(c => !['xx', 'eu', 'un'].includes(c)).map(c => c.toUpperCase()).sort();
  writeFileSync('countries.py', `"""Country codes the app accepts from the AI (ISO 3166-1 alpha-2, plus XK for Kosovo).

Generated by scripts/vendor-assets.mjs from the flags that are vendored in static/vendor/flag-icons, so that every
accepted code has a flag to show. Do not edit by hand; run \`npm run vendor\`.
"""
CODES = frozenset("""
${countries.join(' ')}
""".split())
`);
  console.log(`flag-icons ${version('flag-icons')} -> ${to} (${codes.length} flags, ${countries.length} country codes -> countries.py)`);
}
